export const catalogs: Record<Language, Record<TranslationKey, string>> = { es, en }

export function translate(language: Language, key: TranslationKey, params: TranslationParams = {}) {
  const template = catalogs[language][key] ?? es[key]
  return template.replace(/\{(\w+)\}/g, (placeholder, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder
  ))
}
